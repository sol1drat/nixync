#!/usr/bin/env bash
# Install the Nixync agent on a managed machine.
#
#   sudo ./install-agent.sh --server http://192.168.1.10:8000 --machine-id <uuid>
#   sudo ./install-agent.sh --uninstall
#   ./install-agent.sh --dry-run ...        # show what it would install; no root needed
#
# Installs two things:
#   * The daemon as a systemd system service. It starts at boot, restarts if it
#     dies, and being root-owned only root can stop it — the point on a machine
#     someone else administers.
#   * A desktop entry, so "Nixync" appears in the KDE/XFCE applications menu and
#     starts when the user logs in.
#
# On NixOS the service is declared as a module and realised by nixos-rebuild:
# /etc/systemd/system is a symlink into the read-only store, so a unit file
# cannot simply be dropped there.
#
# Register the machine in the host app first; it shows the agent id after "Add device".
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PY="$ROOT/.venv/bin/python"
UNIT_NAME="nixync-agent.service"
UNIT="/etc/systemd/system/$UNIT_NAME"
NIXOS_MODULE="/etc/nixos/nixync-agent.nix"
NIXOS_CONFIG="/etc/nixos/configuration.nix"
CONFIG_DIR="/etc/nixync"
CONFIG="$CONFIG_DIR/agent.toml"
DESKTOP_NAME="nixync-agent.desktop"
PYTHON_PATH="$ROOT/src/back/helpers:$ROOT/src/back/client:$ROOT/src/shared"

SERVER=""; MACHINE_ID=""; UNINSTALL=""; DRY_RUN=""
while [ $# -gt 0 ]; do
    case "$1" in
        --server)     SERVER="$2"; shift 2 ;;
        --machine-id) MACHINE_ID="$2"; shift 2 ;;
        --uninstall)  UNINSTALL="yes"; shift ;;
        --dry-run)    DRY_RUN="yes"; shift ;;
        -h|--help)    sed -n '2,19p' "${BASH_SOURCE[0]}" | sed 's/^# \?//'; exit 0 ;;
        *)            echo "unknown option: $1" >&2; exit 1 ;;
    esac
done

die() { echo "error: $*" >&2; exit 1; }
is_nixos() { [ -e /etc/NIXOS ] || [ -d /etc/nixos ]; }

# Root is needed to install, but not to look: --dry-run has to work without it, or
# nobody can see what this would put on their machine before it does.
if [ -z "$DRY_RUN" ]; then
    [ "$(id -u)" = "0" ] || die "run this with sudo — it installs a system service."
fi

# The desktop entry belongs to whoever will use the machine, not to root.
TARGET_USER="${SUDO_USER:-$(id -un)}"
TARGET_HOME="$(getent passwd "$TARGET_USER" | cut -d: -f6)"
[ -n "$TARGET_HOME" ] || die "could not find a home directory for $TARGET_USER"

emit_nixos_module() {
    cat <<MODULE_EOF
# Generated by Nixync's install-agent.sh. To uninstall, remove the import from
# configuration.nix, delete this file, and run nixos-rebuild switch.
{ config, pkgs, ... }:

{
  systemd.services.nixync-agent = {
    description = "Nixync agent - keeps this machine in step with the Nixync server";
    wantedBy = [ "multi-user.target" ];
    after = [ "network-online.target" ];
    wants = [ "network-online.target" ];
    environment.PYTHONPATH = "$PYTHON_PATH";
    serviceConfig = {
      Type = "simple";
      # Root: it writes /etc/nixos/nixync.nix and runs nixos-rebuild.
      User = "root";
      ExecStart = "$PY -m nixync_agent.daemon --config $CONFIG";
      Restart = "always";
      RestartSec = 10;
      # A rebuild can take a long while; do not kill it partway.
      TimeoutStopSec = 300;
    };
  };
}
MODULE_EOF
}

emit_unit() {
    cat <<UNIT_EOF
[Unit]
Description=Nixync agent - keeps this machine in step with the Nixync server
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=root
Environment=PYTHONPATH=$PYTHON_PATH
ExecStart=$PY -m nixync_agent.daemon --config $CONFIG
Restart=always
RestartSec=10
TimeoutStopSec=300

[Install]
WantedBy=multi-user.target
UNIT_EOF
}

emit_desktop() {
    cat <<DESKTOP_EOF
[Desktop Entry]
Type=Application
Name=Nixync
GenericName=Managed software
Comment=Request software and see how this machine is doing
Exec=env PYTHONPATH=$PYTHON_PATH $PY -m nixync_agent.gui
Icon=$ROOT/src/shared/nixync_ui/icons/app-icon.png
Terminal=false
Categories=System;Utility;
Keywords=nixos;packages;software;nixync;
StartupNotify=true
DESKTOP_EOF
}

add_import() {
    # Insert ./nixync-agent.nix into the imports list, once.
    "$PY" -c '
import re, sys
path = sys.argv[1]
text = open(path).read()
if "./nixync-agent.nix" in text:
    sys.exit(0)
match = re.search(r"imports\s*=\s*\[(?P<body>.*?)\]", text, re.DOTALL)
if match:
    body = match.group("body").rstrip()
    text = text[: match.start()] + "imports = [" + body + " ./nixync-agent.nix ]" + text[match.end():]
else:
    opening = text.index("{", text.index(":") + 1)
    text = text[: opening + 1] + "\n  imports = [ ./nixync-agent.nix ];\n" + text[opening + 1 :]
open(path, "w").write(text)
' "$1"
}

if [ -n "$UNINSTALL" ]; then
    echo "Removing the Nixync agent..."
    systemctl disable --now "$UNIT_NAME" 2>/dev/null || true
    if is_nixos; then
        rm -f "$NIXOS_MODULE"
        if grep -q "nixync-agent.nix" "$NIXOS_CONFIG" 2>/dev/null; then
            sed -i 's| \./nixync-agent\.nix||' "$NIXOS_CONFIG"
            echo "Removed the import from $NIXOS_CONFIG"
        fi
        echo "Running nixos-rebuild switch to retire the service..."
        nixos-rebuild switch || echo "warning: nixos-rebuild failed; run it yourself to finish."
    else
        rm -f "$UNIT"
        systemctl daemon-reload
    fi
    rm -f "$TARGET_HOME/.local/share/applications/$DESKTOP_NAME"
    rm -f "$TARGET_HOME/.config/autostart/$DESKTOP_NAME"
    echo "Removed the service and the desktop entries."
    echo "Left alone: $CONFIG_DIR, and anything already written to /etc/nixos by the agent."
    echo "To detach this machine completely, also remove ./nixync.nix from"
    echo "$NIXOS_CONFIG and delete /etc/nixos/nixync.nix."
    exit 0
fi

[ -x "$PY" ] || die "no .venv at $PY - run 'nix develop' and install requirements.txt first."

# Fall back to an existing config so a reinstall needs no arguments.
if [ -z "$SERVER" ] && [ -r "$CONFIG" ]; then
    SERVER=$(sed -n 's/^server_url *= *"\(.*\)"/\1/p' "$CONFIG")
    MACHINE_ID=${MACHINE_ID:-$(sed -n 's/^machine_id *= *"\(.*\)"/\1/p' "$CONFIG")}
fi
[ -n "$SERVER" ] || die "no --server given and none in $CONFIG"
[ -n "$MACHINE_ID" ] || die "no --machine-id given and none in $CONFIG"

if [ -n "$DRY_RUN" ]; then
    if is_nixos; then
        echo "=== $NIXOS_MODULE (imported from $NIXOS_CONFIG, applied by nixos-rebuild) ==="
        emit_nixos_module
    else
        echo "=== $UNIT ==="
        emit_unit
    fi
    echo
    echo "=== $TARGET_HOME/.local/share/applications/$DESKTOP_NAME ==="
    echo "=== $TARGET_HOME/.config/autostart/$DESKTOP_NAME ==="
    emit_desktop
    exit 0
fi

echo "Installing the Nixync agent"
echo "  server   $SERVER"
echo "  machine  $MACHINE_ID"
echo "  for      $TARGET_USER"
echo

install -d -m 755 "$CONFIG_DIR"
printf 'server_url = "%s"\nmachine_id = "%s"\n' "$SERVER" "$MACHINE_ID" > "$CONFIG"
chmod 644 "$CONFIG"
echo "Wrote $CONFIG"

if is_nixos; then
    emit_nixos_module > "$NIXOS_MODULE"
    chmod 644 "$NIXOS_MODULE"
    echo "Wrote $NIXOS_MODULE"
    add_import "$NIXOS_CONFIG"
    echo "Imported it from $NIXOS_CONFIG"
    echo "Running nixos-rebuild switch - this is how the service gets created..."
    if ! nixos-rebuild switch; then
        die "nixos-rebuild failed. The module and its import are in place; fix the error
       above and run 'sudo nixos-rebuild switch', or undo it with --uninstall."
    fi
else
    emit_unit > "$UNIT"
    chmod 644 "$UNIT"
    systemctl daemon-reload
    systemctl enable --now "$UNIT_NAME"
fi
echo "Installed and started $UNIT_NAME"

for dir in "$TARGET_HOME/.local/share/applications" "$TARGET_HOME/.config/autostart"; do
    install -d -o "$TARGET_USER" -g "$(id -gn "$TARGET_USER")" -m 755 "$dir"
    emit_desktop > "$dir/$DESKTOP_NAME"
    chown "$TARGET_USER:$(id -gn "$TARGET_USER")" "$dir/$DESKTOP_NAME"
    chmod 644 "$dir/$DESKTOP_NAME"
done
echo "Added Nixync to $TARGET_USER's applications menu, and to login autostart."

# KDE and XFCE cache the menu; without this the entry can take a re-login to appear.
if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "$TARGET_HOME/.local/share/applications" 2>/dev/null || true
fi

echo
echo "Done. The daemon runs as root, so stopping it needs root:"
echo "    sudo systemctl stop $UNIT_NAME"
echo "Follow what it is doing with:"
echo "    journalctl -u $UNIT_NAME -f"
echo "Remove everything with:"
echo "    sudo $ROOT/install-agent.sh --uninstall"
